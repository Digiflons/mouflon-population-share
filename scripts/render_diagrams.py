"""Render every Mermaid diagram in our Markdown docs to SVG files in docs/diagrams/.

Run after changing a diagram: ``python scripts/render_diagrams.py``. Needs the Mermaid
CLI (``mmdc``). The Mermaid text in the Markdown stays the reference; the SVGs are
generated and committed so the diagrams can be viewed anywhere.
"""

import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "diagrams"
SOURCES = [
    ROOT / "README.md",
    *sorted((ROOT / "docs").glob("*.md")),
    *sorted((ROOT / "docs" / "architecture").glob("*.md")),
]
BLOCK = re.compile(r"```mermaid\n(.*?)```", re.DOTALL)
CONFIG = '{"theme": "neutral", "flowchart": {"htmlLabels": false}}'


def main() -> int:
    mmdc = shutil.which("mmdc")
    if not mmdc:
        print("mmdc not found: npm install -g @mermaid-js/mermaid-cli", file=sys.stderr)
        return 1
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    index = [
        "# Diagrams",
        "",
        "Generated by `python scripts/render_diagrams.py` from the Mermaid blocks in "
        "the docs. Edit the docs, not these files.",
        "",
    ]
    count = 0
    with tempfile.TemporaryDirectory() as tmp:
        cfg = Path(tmp) / "config.json"
        cfg.write_text(CONFIG)
        puppeteer = Path(tmp) / "puppeteer.json"
        puppeteer.write_text('{"args": ["--no-sandbox"]}')
        for src in SOURCES:
            blocks = BLOCK.findall(src.read_text(encoding="utf-8"))
            if not blocks:
                continue
            rel = src.relative_to(ROOT)
            stem = "-".join(rel.with_suffix("").parts).lower().replace("docs-", "")
            link = os.path.relpath(src, OUT).replace(os.sep, "/")
            index += [f"## [{rel}]({link})", ""]
            for i, code in enumerate(blocks, 1):
                mmd = Path(tmp) / "in.mmd"
                mmd.write_text(code, encoding="utf-8")
                name = f"{stem}-{i}.svg"
                subprocess.run(
                    [
                        mmdc,
                        "-q",
                        "-i",
                        str(mmd),
                        "-o",
                        str(OUT / name),
                        "-c",
                        str(cfg),
                        "-p",
                        str(puppeteer),
                        "-b",
                        "white",
                    ],
                    check=True,
                )
                index += [f"![{name}]({name})", ""]
                count += 1
    (OUT / "README.md").write_text("\n".join(index), encoding="utf-8")
    print(f"Rendered {count} diagrams to {OUT.relative_to(ROOT)}/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
